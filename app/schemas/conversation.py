"""Pydantic schemas for Conversation lifecycle, multi-turn dialogue, and history."""

from datetime import datetime
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, Field

from app.core.dialogue.state_machine import DialogueState
from app.schemas.extraction import Intent


class CreateConversationRequest(BaseModel):
    """Payload to initiate a new farmer conversation session."""

    language: str = Field(default="kn", description="Language code (default 'kn')")
    initial_intent: Optional[Intent] = Field(default=None, description="Optional stated initial intent")


class ConversationResponse(BaseModel):
    """Full metadata and current state for a conversation session."""

    conversation_id: str
    farmer_id: str
    status: str
    state: DialogueState
    language: str
    current_intent: Optional[str] = None
    summary: Optional[str] = None
    profile: Optional[Dict[str, Any]] = None
    missing_slots: List[str] = Field(default_factory=list)
    conflicts: List[str] = Field(default_factory=list)
    next_question: Optional[str] = None
    version: int
    last_activity_at: datetime
    created_at: datetime


class ConversationListResponse(BaseModel):
    """List of conversations belonging to an authenticated farmer."""

    conversations: List[ConversationResponse]
    total: int


class TurnTextRequest(BaseModel):
    """Payload for submitting a written or transcribed text turn."""

    text: str = Field(min_length=1, max_length=1000, description="Farmer message in Kannada or English")
    language: str = Field(default="kn", description="Language code (default 'kn')")
    client_turn_id: Optional[str] = Field(default=None, description="Idempotency key generated by client")
    expected_version: Optional[int] = Field(default=None, description="Expected conversation version for optimistic locking")


class ConversationTurnDTO(BaseModel):
    """Historical representation of an individual conversation turn."""

    turn_id: str
    turn_number: int
    role: str
    input_mode: str
    transcript_text: Optional[str] = None
    assistant_text: Optional[str] = None
    audio_url: Optional[str] = None
    created_at: datetime


class ConversationHistoryResponse(BaseModel):
    """Chronological history of conversation turns."""

    conversation_id: str
    turns: List[ConversationTurnDTO]
    total_turns: int


class TurnResponse(BaseModel):
    """Result of processing a conversation turn."""

    turn_id: str
    turn_number: int
    conversation_id: str
    dialogue_state: DialogueState
    transcript_text: str
    assistant_text: str
    audio_url: Optional[str] = None
    speech_available: bool = True
    missing_slots: List[str] = Field(default_factory=list)
    next_required_slot: Optional[str] = None
    is_ready_for_evaluation: bool = False
    conflicts: List[str] = Field(default_factory=list)
    extracted_intent: Optional[str] = None
    version: int
